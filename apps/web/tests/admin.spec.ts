import AxeBuilder from '@axe-core/playwright';
import { expect, test } from '@playwright/test';

test('adds demo domains, users, aliases and moderated groups', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('searchbox')).toBeEnabled();
  const historySize = await page.evaluate(() => history.length);
  await page.getByRole('link', { name: 'Riaklo Mail' }).click();
  expect(await page.evaluate(() => history.length)).toBe(historySize);
  const admin = page.getByRole('button', { name: 'Mail admin', exact: true });
  if (!(await admin.isVisible())) await page.getByRole('button', { name: 'Navigation menu' }).click();
  await admin.click();
  await expect(page.getByRole('heading', { name: 'Domains', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Add domain', exact: true }).click();
  await page.getByLabel('Domain name').fill('sales.example.com');
  await page.getByLabel('Domain type').selectOption('Alias');
  await page.getByRole('button', { name: 'Save domain' }).click();
  await expect(page.getByRole('row', { name: /sales\.example\.com.*Alias.*Pending/ })).toBeVisible();
  await page.getByRole('button', { name: 'Users and aliases', exact: true }).click();
  await page.getByRole('button', { name: 'Add user', exact: true }).click();
  await page.getByLabel('Display name').fill('Jamie Ford');
  await page.getByLabel('User email').fill('jamie@example.com');
  await page.getByRole('button', { name: 'Save user' }).click();
  await page.getByRole('button', { name: 'Add alias', exact: true }).click();
  await page.getByRole('combobox', { name: 'User', exact: true }).selectOption('jamie@example.com');
  await page.getByLabel('Alias email').fill('sales@example.com');
  await page.getByRole('button', { name: 'Save alias' }).click();
  await expect(page.getByRole('row', { name: /Jamie Ford.*sales@example\.com/ })).toBeVisible();
  await page.getByRole('button', { name: 'Groups', exact: true }).click();
  await page.getByRole('button', { name: 'Add group', exact: true }).click();
  await page.getByLabel('Group name').fill('Operations');
  await page.getByLabel('Group email').fill('ops@example.com');
  await page.getByLabel('Moderate posts').check();
  await page.getByRole('button', { name: 'Save group' }).click();
  await expect(page.getByRole('row', { name: /Operations.*ops@example\.com.*Moderated/ })).toBeVisible();
  expect((await new AxeBuilder({ page }).analyze()).violations.filter((v) => v.impact === 'serious' || v.impact === 'critical')).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width);
  const home = page.getByRole('link', { name: 'Riaklo Mail' });
  await home.click();
  await expect(page.getByRole('heading', { name: 'Inbox' })).toBeVisible();
  await page.getByRole('button', { name: /^Mira Chen.*Floor plan revisions/ }).click();
  await home.click();
  await expect(page.getByRole('heading', { name: 'Inbox' })).toBeVisible();
  await page.goBack();
  await expect(page.getByRole('heading', { name: 'Domains', exact: true })).toBeVisible();
});
