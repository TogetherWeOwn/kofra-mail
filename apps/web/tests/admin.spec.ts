import AxeBuilder from '@axe-core/playwright';
import { expect, test } from './fixtures/mail';

test('admin adds a domain, assigns a mailbox to a workspace member and creates an alias', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('searchbox')).toBeEnabled();
  const historySize = await page.evaluate(() => history.length);
  const home = page.getByRole('link', { name: 'Riaklo Mail' });
  await home.click();
  expect(await page.evaluate(() => history.length)).toBe(historySize);
  const admin = page.getByRole('button', { name: 'Mail admin', exact: true });
  if (!(await admin.isVisible())) await page.getByRole('button', { name: 'Navigation menu' }).click();
  await admin.click();
  await expect(page.getByRole('heading', { name: 'Domains', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Add domain', exact: true }).click();
  await page.getByLabel('Domain name').fill('sales.example.com');
  await page.getByLabel('Domain type').selectOption('alias');
  await page.getByLabel('Alias target').selectOption('example.com');
  const domain = page.waitForResponse((res) => new URL(res.url()).pathname.endsWith('/domains') && res.request().method() === 'POST');
  await page.getByRole('button', { name: 'Save domain' }).click();
  expect((await domain).request().headers()['idempotency-key']).toMatch(/^[0-9a-f-]{36}$/);
  await expect(page.getByRole('row', { name: /sales\.example\.com.*Alias.*Pending/i })).toBeVisible();
  await page.getByRole('button', { name: 'Mailboxes and aliases', exact: true }).click();
  await page.getByRole('button', { name: 'Add mailbox', exact: true }).click();
  await page.getByLabel('Display name').fill('Jamie Ford');
  await page.getByLabel('Mailbox address').fill('jamie@example.com');
  await page.getByRole('combobox', { name: 'Workspace member' }).selectOption({ label: 'An invitee (invited@example.com)' });
  const mailbox = page.waitForResponse((res) => new URL(res.url()).pathname.endsWith('/mailboxes') && res.request().method() === 'POST');
  await page.getByRole('button', { name: 'Save mailbox' }).click();
  const added = await mailbox;
  expect(added.request().postDataJSON().ownerUserId).toBe('invited');
  const mailboxId = (await added.json()).id;
  await expect(page.getByRole('row', { name: /Jamie Ford.*jamie@example\.com/ })).toBeVisible();
  await page.getByRole('button', { name: 'Add alias', exact: true }).click();
  await page.getByRole('combobox', { name: 'Mailbox', exact: true }).selectOption(mailboxId);
  await page.getByLabel('Alias address').fill('sales@example.com');
  await page.getByRole('button', { name: 'Save alias' }).click();
  await expect(page.getByRole('row', { name: /Jamie Ford.*sales@example\.com/ })).toBeVisible();
  expect((await new AxeBuilder({ page }).analyze()).violations.filter((v) => v.impact === 'serious' || v.impact === 'critical')).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width);
  await home.click();
  await expect(page.getByRole('heading', { name: 'Inbox' })).toBeVisible();
  await page.getByRole('button', { name: /^Mira Chen.*Floor plan revisions/ }).click();
  await home.click();
  await expect(page.getByRole('heading', { name: 'Inbox' })).toBeVisible();
  await page.goBack();
  await expect(page.getByRole('heading', { name: 'Domains', exact: true })).toBeVisible();
});
